/** Extras, part one: `links`, its JSON keys, scope filtering, sensitivity counts and its output file. */

import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import { test } from "node:test";
import { type Brain, Sandbox } from "./harness.ts";

// Parsed JSON reports: the tests index into them freely, as the Python suite did.
type Json = any; // eslint-disable-line @typescript-eslint/no-explicit-any

/** Today's local date as YYYY-MM-DD (Python's date.today()). */
function isoDate(): string {
  const date = new Date();
  return date.getFullYear() + "-" + String(date.getMonth() + 1).padStart(2, "0") + "-"
    + String(date.getDate()).padStart(2, "0");
}

const TODAY = isoDate();
const LINK_KEYS = ["time_links", "entity_links", "collisions", "sensitive_files", "sensitive_topics"];

function doc(title: string, body = "body", { extra = "", updated = TODAY, status = "active" } = {}): string {
  return "---\nupdated: " + updated + "\nstatus: " + status + "\nkey_fact: K.\nsummary: K.\naliases: []\nperiod: []\n"
    + "entities: []\n" + extra + "---\n\n# " + title + "\n\n" + body + "\n";
}

function topic(target: Brain, name: string, scope: string, body = "body", { extra = "", updated = TODAY } = {}): void {
  target.write("topics/" + name + "/README.md", doc(name, "readme", { extra: "scope: " + scope + "\n", updated }));
  target.write("topics/" + name + "/note.md", doc(name + " note", body, { extra, updated }));
}

function linksJson(target: Brain, ...args: string[]): Json {
  const result = target.run(["links", "--json", ...args]);
  assert.equal(result.code, 0, result.err);
  return JSON.parse(result.out);
}

function monthLink(report: Json, month: string): Json {
  return report.time_links.find((item: Json) => item.month === month) ?? null;
}

function brain(): Brain {
  return new Sandbox().brain();
}

test("links --json has the report keys", () => {
  assert.deepEqual(Object.keys(linksJson(brain())), LINK_KEYS);
});

test("links --json is pretty printed", () => {
  const out = brain().run(["links", "--json"]).out;
  assert.ok(out.startsWith('{\n  "time_links": ['));
  assert.ok(out.endsWith("}\n"));
});

test("links of an empty brain is empty", () => {
  assert.deepEqual(linksJson(brain()), {
    time_links: [], entity_links: [], collisions: [], sensitive_files: 0, sensitive_topics: 0,
  });
});

test("links writes the map next to the config", () => {
  const b = brain();
  const result = b.run(["links"]);
  assert.deepEqual([result.code, result.out], [0, "LINKS.md written.\n"]);
  const text = b.read("LINKS.md");
  assert.ok(text.startsWith("Generated by rcllr on " + TODAY + ". Do not edit by hand.\n\n## Time links\n"));
  assert.ok(text.includes("\n## Entity links\n"));
  assert.ok(text.includes("\n## Collisions\n"));
  assert.ok(text.endsWith("0 sensitive files and 0 sensitive topics excluded.\n"));
});

test("links --json does not write the map", () => {
  const b = brain();
  linksJson(b);
  assert.ok(!b.exists("LINKS.md"));
});

test("topics sharing a month in their text are linked", () => {
  const b = brain();
  topic(b, "alpha", "work", "Kickoff 2025-03-04.");
  topic(b, "beta", "work", "Review 2025-03-20.");
  const link = monthLink(linksJson(b), "2025-03");
  assert.deepEqual(link, { month: "2025-03", topic_count: 2, topics: ["topics/alpha", "topics/beta"] });
});

for (const text of ["Kickoff 2025-03-04.", "Kickoff in March 2025.", "Kickoff in Mar 2025.", "Kickoff 3/2025."]) {
  test("month format is recognized: " + text, () => {
    const b = brain();
    topic(b, "alpha", "work", text);
    topic(b, "beta", "work", "Also 2025-03-09.");
    assert.notEqual(monthLink(linksJson(b), "2025-03"), null);
  });
}

test("period in the frontmatter counts as a month", () => {
  const b = brain();
  topic(b, "alpha", "work", undefined, { extra: "period: [2025-07]\n" });
  topic(b, "beta", "work", "Mentioned in July 2025.");
  assert.notEqual(monthLink(linksJson(b), "2025-07"), null);
});

test("a month in one topic only is not a link", () => {
  const b = brain();
  topic(b, "alpha", "work", "Only 2025-04-01 here.");
  topic(b, "beta", "work", "Nothing dated.");
  assert.equal(monthLink(linksJson(b), "2025-04"), null);
});

test("--min-topics raises the bar for links", () => {
  const b = brain();
  topic(b, "alpha", "work", "Kickoff 2025-03-04.");
  topic(b, "beta", "work", "Review 2025-03-20.");
  assert.equal(monthLink(linksJson(b, "--min-topics", "3"), "2025-03"), null);
  assert.notEqual(monthLink(linksJson(b, "--min-topics", "2"), "2025-03"), null);
});

test("min_topics comes from the config", () => {
  const b = brain();
  b.configure("[links]\nmin_topics = 3\n");
  topic(b, "alpha", "work", "Kickoff 2025-03-04.");
  topic(b, "beta", "work", "Review 2025-03-20.");
  assert.equal(monthLink(linksJson(b), "2025-03"), null);
});

test("time links are listed newest month first", () => {
  const b = brain();
  topic(b, "alpha", "work", "2024-01-05 and 2025-06-05.");
  topic(b, "beta", "work", "2024-01-06 and 2025-06-06.");
  const months: string[] = linksJson(b).time_links.map((item: Json) => item.month);
  assert.deepEqual(months, [...months].sort().reverse());
  assert.ok(months.includes("2024-01") && months.includes("2025-06"));
});

test("entities file links topics that mention an entity", () => {
  const b = brain();
  b.write("entities.txt", "# comment\nAcme|acme corp\ni:globex\n");
  topic(b, "alpha", "work", "We talk to acme corp.");
  topic(b, "beta", "work", "Acme is a client.");
  topic(b, "gamma", "work", "GLOBEX and Globex.");
  topic(b, "delta", "work", "globex too.");
  const entities = Object.fromEntries(linksJson(b).entity_links.map((item: Json) => [item.entity, item]));
  assert.deepEqual(new Set(entities.Acme.topics), new Set(["topics/alpha", "topics/beta"]));
  assert.deepEqual(new Set(entities.globex.topics), new Set(["topics/gamma", "topics/delta"]));
});

test("entity names are case sensitive without the i: prefix", () => {
  const b = brain();
  b.write("entities.txt", "Acme|ACME Corp\n");
  topic(b, "alpha", "work", "Acme builds it.");
  topic(b, "beta", "work", "ACME Corp pays.");
  topic(b, "gamma", "work", "acme in lowercase.");
  const entity = linksJson(b).entity_links[0];
  assert.equal(entity.entity, "Acme");
  assert.deepEqual(new Set(entity.topics), new Set(["topics/alpha", "topics/beta"]));
});

test("entity listed in the frontmatter counts without a mention", () => {
  const b = brain();
  b.write("entities.txt", "Acme\n");
  topic(b, "alpha", "work", "No name in the text.", { extra: "entities: [Acme]\n" });
  topic(b, "beta", "work", "Acme here.");
  assert.equal(linksJson(b).entity_links[0].topic_count, 2);
});

test("collisions name months busy on both sides of a scope barrier", () => {
  const b = brain();
  topic(b, "job", "work", "Deadline 2025-05-01.");
  topic(b, "home", "private", "Holiday 2025-05-10.");
  const collision = linksJson(b).collisions.find((item: Json) => item.month === "2025-05");
  assert.ok(collision !== undefined);
  assert.deepEqual(collision, { month: "2025-05", scopes: { work: ["job"], private: ["home"] } });
});

test("no collision when both topics share a scope", () => {
  const b = brain();
  topic(b, "job", "work", "Deadline 2025-05-01.");
  topic(b, "other", "work", "Deadline 2025-05-02.");
  assert.deepEqual(linksJson(b).collisions.filter((item: Json) => item.month === "2025-05"), []);
});

test("collisions follow the configured barriers", () => {
  const b = brain();
  b.configure("[scopes]\nlink_barriers = []\n");
  topic(b, "job", "work", "Deadline 2025-05-01.");
  topic(b, "home", "private", "Holiday 2025-05-10.");
  assert.deepEqual(linksJson(b).collisions, []);
});

test("collisions ignore --min-topics", () => {
  const b = brain();
  topic(b, "job", "work", "Deadline 2025-05-01.");
  topic(b, "home", "private", "Holiday 2025-05-10.");
  const report = linksJson(b, "--min-topics", "5");
  assert.equal(monthLink(report, "2025-05"), null);
  assert.ok(report.collisions.some((item: Json) => item.month === "2025-05"));
});

test("links leave sensitive notes out and count them", () => {
  const b = brain();
  topic(b, "alpha", "work", "Kickoff 2025-03-04.");
  topic(b, "beta", "work", "Review 2025-03-20.");
  topic(b, "vault", "private", "Secret 2025-03-30.\n\n> SENSITIVE");
  b.write("notes/loose.md", doc("Loose", "> SENSITIVE\n\n2025-03-31"));
  const report = linksJson(b);
  const link = monthLink(report, "2025-03");
  assert.notEqual(link, null);
  assert.deepEqual(link.topics, ["topics/alpha", "topics/beta"]);
  assert.equal(report.sensitive_files, 2);
  assert.equal(report.sensitive_topics, 0);
});

test("links count topics hidden by a marked README", () => {
  const b = brain();
  b.write("topics/vault/README.md", doc("Vault", "> SENSITIVE", { extra: "scope: private\n" }));
  b.write("topics/vault/page.md", doc("Page", "2025-03-30"));
  const report = linksJson(b);
  assert.deepEqual([report.sensitive_files, report.sensitive_topics], [2, 1]);
  assert.ok(!JSON.stringify(report).includes("vault"));
});

test("links leave paths listed in the paths file out", () => {
  const b = brain();
  topic(b, "alpha", "work", "Kickoff 2025-03-04.");
  topic(b, "listed", "work", "Review 2025-03-20.");
  b.write(".sensitive-paths", "topics/listed/\n");
  assert.equal(monthLink(linksJson(b), "2025-03"), null);
});

test("links --scope keeps only that scope and mixed notes", () => {
  const b = brain();
  topic(b, "job", "work", "Deadline 2025-05-01.");
  topic(b, "other", "work", "Deadline 2025-05-02.");
  topic(b, "home", "private", "Holiday 2025-05-10.");
  const work = linksJson(b, "--scope", "work");
  assert.deepEqual(monthLink(work, "2025-05"), { month: "2025-05", topic_count: 2, topics: ["topics/job", "topics/other"] });
  assert.deepEqual(work.collisions, []);
  assert.equal(monthLink(linksJson(b, "--scope", "both"), "2025-05").topic_count, 3);
});

test("links scope defaults to the configured query_default", () => {
  const b = brain();
  b.configure('[scopes]\nquery_default = "work"\n');
  topic(b, "job", "work", "Deadline 2025-05-01.");
  topic(b, "other", "work", "Deadline 2025-05-02.");
  topic(b, "home", "private", "Holiday 2025-05-10.");
  assert.equal(monthLink(linksJson(b), "2025-05").topic_count, 2);
});

test("links rejects an unknown scope", () => {
  const result = brain().run(["links", "--scope", "nowhere"]);
  assert.equal(result.code, 2);
  assert.equal(result.err, "Invalid scope. Use one of: both, private, work.\n");
});

test("links --out writes to another markdown file", () => {
  const b = brain();
  fs.mkdirSync(path.join(b.root, "maps"));
  const result = b.run(["links", "--out", "maps/graph.md"]);
  assert.deepEqual([result.code, result.out], [0, "maps/graph.md written.\n"]);
  assert.ok(b.exists("maps/graph.md"));
  assert.ok(!b.exists("LINKS.md"));
});

for (const target of ["notes/links.md", "topics/links.md", "../outside.md", "missing-folder/x.md", "links.txt",
  ".git/links.md"]) {
  test("links --out " + target + " is refused: it must be a markdown file in an existing folder outside the notes",
    () => {
      const b = brain();
      fs.mkdirSync(path.join(b.root, "notes"));
      fs.mkdirSync(path.join(b.root, "topics"));
      fs.mkdirSync(path.join(b.root, ".git"));
      const result = b.run(["links", "--out", target]);
      assert.equal(result.code, 2);
      assert.equal(result.err, target + ": the links file must be a .md file inside the brain, in an existing folder, "
        + "outside .git and outside the note folders.\n");
    });
}

test("links output comes from the config", () => {
  const b = brain();
  b.configure('[links]\noutput = "MAP.md"\n');
  assert.equal(b.run(["links"]).out, "MAP.md written.\n");
});

test("links map is not searchable", () => {
  const b = brain();
  topic(b, "alpha", "work", "Kickoff 2025-03-04.");
  b.run(["links"]);
  assert.deepEqual(JSON.parse(b.run(["find", "Generated", "--json"]).out).hits, []);
});

test("German locale writes a German map", () => {
  const b = brain();
  b.configure('[ui]\nlocale = "de"\n');
  b.run(["links"]);
  const text = b.read("LINKS.md");
  assert.ok(text.startsWith("Generiert von rcllr am " + TODAY + ". Nicht von Hand pflegen.\n"));
  assert.ok(text.includes("## Zeit-Kanten"));
  assert.ok(text.includes("## Kollisionen"));
});
