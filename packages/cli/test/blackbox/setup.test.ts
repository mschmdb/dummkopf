/** `init` and `install`: the scaffold, the Git hook and the Claude Code and Codex hook files. */

import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as path from "node:path";
import { test } from "node:test";
import { Sandbox } from "./harness.ts";

const REMOTE = "git@github.com:me/brain.git";
const CLAUDE_HOOK = 'dummkopf --root "$CLAUDE_PROJECT_DIR" hook agent';
const CODEX_HOOK = 'dummkopf --root "$(git rev-parse --show-toplevel)" hook agent';
const INSTALLED = "Installed: .git/hooks/pre-commit\nInstalled: .claude/settings.json\nInstalled: .codex/hooks.json\n";

// Parsed JSON settings files: the tests index into them freely, as the Python suite did.
type Json = any; // eslint-disable-line @typescript-eslint/no-explicit-any

function initBrain(sandbox: Sandbox, name = "newbrain", ...args: string[]): string {
  const result = sandbox.run(["init", path.join(sandbox.tmp, name), "--serious", ...args], { cwd: sandbox.tmp });
  assert.equal(result.code, 0, result.err);
  return path.join(sandbox.tmp, name);
}

/** A brain made by `init --remote`, the `fresh` fixture. */
function fresh(): { sandbox: Sandbox; root: string } {
  const sandbox = new Sandbox();
  return { sandbox, root: initBrain(sandbox, "newbrain", "--remote", REMOTE) };
}

function read(root: string, rel: string): string {
  return fs.readFileSync(path.join(root, rel), "utf-8");
}

function settings(root: string, name = ".claude/settings.json"): Json {
  return JSON.parse(read(root, name));
}

function commands(entries: Json[]): string[] {
  return entries.flatMap((entry: Json) => entry.hooks.map((hook: Json) => hook.command as string));
}

// --- init -----------------------------------------------------------------------------------------------------

test("init creates the scaffold", () => {
  const sandbox = new Sandbox();
  const root = initBrain(sandbox);
  const names = (fs.readdirSync(root, { recursive: true }) as string[])
    .filter((name) => !name.split(path.sep).includes(".git"))
    .map((name) => name.split(path.sep).join("/"))
    .sort();
  assert.deepEqual(names, [".gitignore", ".sensitive-paths", "AGENTS.md", "CLAUDE.md", "INDEX.md", "archive",
    "archive/.gitkeep", "bookmarks", "bookmarks/.gitkeep", "dummkopf.toml", "notes",
    "notes/.gitkeep", "sources", "sources/.gitkeep", "topics", "topics/.gitkeep"]);
});

test("init prints next steps without a remote", () => {
  const sandbox = new Sandbox();
  const result = sandbox.run(["init", path.join(sandbox.tmp, "newbrain"), "--serious"], { cwd: sandbox.tmp });
  assert.equal(result.code, 0);
  assert.ok(result.out.startsWith("New brain created in "));
  assert.ok(result.out.endsWith(". Next: set repo.remote in dummkopf.toml, then `dummkopf install`.\n"));
});

test("init prints next steps with a remote", () => {
  const sandbox = new Sandbox();
  const result = sandbox.run(["init", path.join(sandbox.tmp, "newbrain"), "--serious", "--remote", REMOTE],
    { cwd: sandbox.tmp });
  assert.ok(result.out.endsWith(". Next: `dummkopf install`, then commit and push.\n"));
});

