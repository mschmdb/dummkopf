// --- install ----------------------------------------------------------------------------------------------------

test("install reports what it wrote", () => {
  const { sandbox, root } = fresh();
  const result = sandbox.run(["install", "--serious"], { cwd: root });
  assert.deepEqual([result.code, result.out, result.err], [0, INSTALLED, ""]);
});

test("install writes an executable managed pre-commit hook", () => {
  const { sandbox, root } = fresh();
  sandbox.run(["install"], { cwd: root });
  const hook = path.join(root, ".git", "hooks", "pre-commit");
  const text = fs.readFileSync(hook, "utf-8");
  assert.ok(text.startsWith("#!/bin/sh\n# managed-by: dummkopf\n"));
  assert.ok(text.includes("dummkopf hook pre-commit"));
  assert.ok(text.trimEnd().endsWith("exit 0"));
  assert.ok((fs.statSync(hook).mode & 0o111) !== 0);
});

test("install wires Claude Code hooks", () => {
  const { sandbox, root } = fresh();
  sandbox.run(["install"], { cwd: root });
  const data = settings(root);
  assert.equal(data.$schema, "https://json.schemastore.org/claude-code-settings.json");
  const post: Json[] = data.hooks.PostToolUse;
  assert.deepEqual(post.map((entry) => entry.matcher), ["Write|Edit|MultiEdit|Bash"]);
  assert.ok(post.every((entry) => entry.hooks.every((hook: Json) => hook.type === "command")));
  assert.deepEqual(commands(post).map((command) => command.endsWith(CLAUDE_HOOK)), [true]);
  const sessionEnd: Json[] = data.hooks.SessionEnd;
  assert.ok(!("matcher" in sessionEnd[0]));
  assert.ok(commands(sessionEnd)[0]!.endsWith(CLAUDE_HOOK));
});

test("install wires Codex hooks", () => {
  const { sandbox, root } = fresh();
  sandbox.run(["install"], { cwd: root });
  const entry = settings(root, ".codex/hooks.json").hooks.PostToolUse[0];
  assert.equal(entry.matcher, "Bash|apply_patch|Edit|Write");
  const hook = entry.hooks[0];
  assert.ok(hook.command.endsWith(CODEX_HOOK));
  assert.equal(hook.timeout, 60);
  assert.equal(hook.statusMessage, "Syncing notes");
});

test("install writes no absolute paths", () => {
  const { sandbox, root } = fresh();
  sandbox.run(["install"], { cwd: root });
  for (const name of [".claude/settings.json", ".codex/hooks.json", ".git/hooks/pre-commit"]) {
    assert.ok(!read(root, name).includes(root), name);
  }
});

test("install twice changes no file", () => {
  const { sandbox, root } = fresh();
  sandbox.run(["install"], { cwd: root });
  const names = [".claude/settings.json", ".codex/hooks.json", ".git/hooks/pre-commit"];
  const snapshot = (): Record<string, Buffer> =>
    Object.fromEntries(names.map((name) => [name, fs.readFileSync(path.join(root, name))]));
  const before = snapshot();
  const again = sandbox.run(["install", "--serious"], { cwd: root });
  assert.equal(again.code, 0);
  assert.equal(again.out, INSTALLED);
  assert.deepEqual(snapshot(), before);
});

test("install keeps existing settings and other hooks", () => {
  const { sandbox, root } = fresh();
  fs.mkdirSync(path.join(root, ".claude"));
  const existing = {
    permissions: { allow: ["Bash(ls)"] },
    hooks: { PostToolUse: [{ matcher: "Bash", hooks: [{ type: "command", command: "keepme" }] }] },
  };
  fs.writeFileSync(path.join(root, ".claude/settings.json"), JSON.stringify(existing), "utf-8");
  sandbox.run(["install"], { cwd: root });
  const data = settings(root);
  assert.deepEqual(data.permissions, { allow: ["Bash(ls)"] });
  assert.ok(commands(data.hooks.PostToolUse).includes("keepme"));
  assert.ok(commands(data.hooks.PostToolUse).some((command) => command.endsWith(CLAUDE_HOOK)));
});

test("install without codex_sync skips the Codex file", () => {
  const { sandbox, root } = fresh();
  fs.appendFileSync(path.join(root, "dummkopf.toml"), "\n[extras]\ncodex_sync = false\n", "utf-8");
  const result = sandbox.run(["install", "--serious"], { cwd: root });
  assert.equal(result.out, "Installed: .git/hooks/pre-commit\nInstalled: .claude/settings.json\n");
  assert.ok(!fs.existsSync(path.join(root, ".codex")));
});

test("install refuses a foreign pre-commit hook", () => {
  const { sandbox, root } = fresh();
  const hook = path.join(root, ".git", "hooks", "pre-commit");
  fs.writeFileSync(hook, "#!/bin/sh\necho mine\n", "utf-8");
  const result = sandbox.run(["install", "--serious"], { cwd: root });
  assert.equal(result.code, 2);
  assert.equal(result.err, ".git/hooks/pre-commit exists and was not written by dummkopf. Merge it by hand: call "
    + "`dummkopf hook pre-commit` from your hook, or move it away and run `dummkopf install` again.\n");
  assert.equal(fs.readFileSync(hook, "utf-8"), "#!/bin/sh\necho mine\n");
  assert.ok(!fs.existsSync(path.join(root, ".claude", "settings.json")), "exit 2 must change nothing");
  assert.ok(!fs.existsSync(path.join(root, ".codex", "hooks.json")));
});

