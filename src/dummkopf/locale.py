"""Language-bound data: heuristics that read note text, and headings dummkopf generates.

CLI messages stay in messages.py (English). This module only changes what dummkopf
reads out of notes and what it writes into generated files, so an existing brain in
another language keeps its INDEX.md and README tables byte-identical.
"""

from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Locale:
    stopwords: frozenset[str]
    this_week: re.Pattern[str]
    next_week: re.Pattern[str]
    negations: frozenset[str]
    without: frozenset[str]
    row_date: re.Pattern[str]
    period_connector: str
    months: dict[str, int]
    day_month_year: re.Pattern[str] | None
    open_words: tuple[str, ...]
    updated_label: re.Pattern[str]
    date_formats: tuple[str, ...]
    archive_hint: str
    files_heading: str
    stub_heading: str
    index_topics: str
    index_notes: str
    index_bookmarks: str
    topic_columns: tuple[str, str, str]
    file_columns: tuple[str, str, str]
    links_generated: str
    links_time: str
    links_entities: str
    links_collisions: str
    links_none: str
    links_topics: str
    links_excluded: str


def _words(text: str) -> frozenset[str]:
    return frozenset(text.split())


EN = Locale(
    stopwords=_words(
        "what how why when where who which whose is are was were does do did there has have had "
        "the a an i you we me my our must should can could would for with from to in on at of by "
        "about after and or it please show tell give me us all anything something still already"
    ),
    this_week=re.compile(r"\bthis week\b"),
    next_week=re.compile(r"\bnext week\b"),
    negations=_words("not no none never"),
    without=_words("without except excluding"),
    row_date=re.compile(r"\b(?:(?P<year>\d{4})-)?(?P<month>\d{1,2})-(?P<day>\d{1,2})\b"),
    period_connector="to",
    months={
        "january": 1, "jan": 1, "february": 2, "feb": 2, "march": 3, "mar": 3, "april": 4, "apr": 4,
        "may": 5, "june": 6, "jun": 6, "july": 7, "jul": 7, "august": 8, "aug": 8,
        "september": 9, "sept": 9, "sep": 9, "october": 10, "oct": 10, "november": 11, "nov": 11,
        "december": 12, "dec": 12,
    },
    day_month_year=None,
    open_words=("open question", "to check", "unverified", "TODO", "TBD", "not yet"),
    updated_label=re.compile(r"(?:As of|Updated):?\s*(\d{4}-\d{2}-\d{2})", re.IGNORECASE),
    date_formats=("%Y-%m-%d",),
    archive_hint="archive",
    files_heading="## Files",
    stub_heading="## Unfiled (auto-stub)",
    index_topics="## Topics",
    index_notes="## Notes (flat)",
    index_bookmarks="## Bookmarks",
    topic_columns=("Folder", "About", "Aliases"),
    file_columns=("File", "Key fact", "Aliases"),
    links_generated="Generated by dummkopf on {date}. Do not edit by hand.",
    links_time="## Time links",
    links_entities="## Entity links",
    links_collisions="## Collisions",
    links_none="None found.",
    links_topics="Topics",
    links_excluded="{files} sensitive files and {topics} sensitive topics excluded.",
)

# German stopwords are ASCII-folded because the search folds umlauts before matching.
DE = Locale(
    stopwords=_words(
        "was wie warum wieso weshalb wann wo wer welche welcher welches ist sind war steht stehen gibt "
        "haben habe hat der die das den dem des ein eine einen einem einer ich du wir mir mich mein "
        "meine meinen muss soll kann fur mit von zu zum zur im in am an auf aus bei uber nach und "
        "oder es bitte zeig zeige machen dazu alles etwas noch schon"
    ),
    this_week=re.compile(r"\bdiese(?:r|n)? woche\b"),
    next_week=re.compile(r"\bnachste(?:n)? woche\b"),
    negations=_words("nicht kein keine keinen keinem keiner"),
    without=_words("ohne"),
    row_date=re.compile(r"\b(?P<day>\d{1,2})\.(?P<month>\d{1,2})\.(?:(?P<year>\d{4})\b)?"),
    period_connector="bis",
    months={
        "januar": 1, "jan": 1, "februar": 2, "feb": 2, "märz": 3, "mär": 3, "mrz": 3,
        "april": 4, "apr": 4, "mai": 5, "juni": 6, "jun": 6, "juli": 7, "jul": 7,
        "august": 8, "aug": 8, "september": 9, "sept": 9, "sep": 9, "oktober": 10, "okt": 10,
        "november": 11, "nov": 11, "dezember": 12, "dez": 12,
    },
    day_month_year=re.compile(r"\b(\d{1,2})\.(\d{1,2})\.(\d{4})\b"),
    open_words=("offen", "offene Frage", "prüfen", "ungeprüft", "TODO", "noch nicht"),
    updated_label=re.compile(r"Stand:?\s*(\d{1,2}\.\d{1,2}\.\d{4}|\d{4}-\d{2}-\d{2})"),
    date_formats=("%Y-%m-%d", "%d.%m.%Y"),
    archive_hint="archiv",
    files_heading="## Dateien",
    stub_heading="## Nicht eingeordnet (auto-stub)",
    index_topics="## Topics",
    index_notes="## Notes (flach)",
    index_bookmarks="## Bookmarks",
    topic_columns=("Ordner", "Worum es geht", "Aliase"),
    file_columns=("Datei", "Kernfakt", "Aliase"),
    links_generated="Generiert von dummkopf am {date}. Nicht von Hand pflegen.",
    links_time="## Zeit-Kanten",
    links_entities="## Entitäts-Kanten",
    links_collisions="## Kollisionen",
    links_none="Keine gefunden.",
    links_topics="Topics",
    links_excluded="{files} sensible Dateien und {topics} sensible Topics ausgeschlossen.",
)

LOCALES = {"en": EN, "de": DE}


def get_locale(name: str) -> Locale:
    return LOCALES[name]
