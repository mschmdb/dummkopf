"""One definition of "sensitive", shared by reading, writing, indexing and the extras.

A note is sensitive when its path is listed in the paths file or under a
`sensitive.always` prefix, when it carries the marker line, or when a README in
one of its folders carries it.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from functools import cached_property, lru_cache
from pathlib import Path

from dummkopf.config import Config
from dummkopf.files import iter_note_files


@lru_cache(maxsize=16)
def marker_pattern(marker: str) -> re.Pattern[str]:
    """`> SENSITIVE` matches `>SENSITIVE` and `>   sensitive` at a line start, never across lines."""
    tokens = marker.split()
    # Any horizontal whitespace, Unicode included: a non-breaking space renders like a space.
    return re.compile("^" + r"[^\S\r\n]*".join(re.escape(token) for token in tokens),
                      re.IGNORECASE | re.MULTILINE)


def split_entries(entries: list[str] | tuple[str, ...]) -> tuple[frozenset[str], frozenset[str]]:
    files: set[str] = set()
    dirs: set[str] = set()
    for raw in entries:
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.endswith("/") or not line.endswith(".md"):
            dirs.add(line.rstrip("/"))
        else:
            files.add(line)
    return frozenset(files), frozenset(dirs)


@dataclass(frozen=True)
class Sensitivity:
    root: Path
    pattern: re.Pattern[str]
    readme: str
    files: frozenset[str]
    dirs: frozenset[str]
    always_files: frozenset[str]
    always_dirs: frozenset[str]

    @classmethod
    def load(cls, config: Config, listed: list[str] | None = None) -> Sensitivity:
        """Read the paths file. A missing file counts as empty; Access enforces its presence."""
        if listed is None:
            path = config.root / config.sensitive.paths_file
            listed = path.read_text(encoding="utf-8").splitlines() if path.is_file() else []
        files, dirs = split_entries(listed)
        always_files, always_dirs = split_entries(config.sensitive.always)
        return cls(config.root, marker_pattern(config.sensitive.marker), config.layout.topic_readme,
                   files, dirs, always_files, always_dirs)

    @cached_property
    def _folded(self) -> tuple[frozenset[str], frozenset[str], frozenset[str], frozenset[str]]:
        """Case-folded entries: a case-insensitive file system opens `Health/` for `health/`."""
        return tuple(frozenset(entry.casefold() for entry in group)  # type: ignore[return-value]
                     for group in (self.files, self.dirs, self.always_files, self.always_dirs))

    def is_listed(self, rel: str) -> bool:
        files, dirs, always_files, always_dirs = self._folded
        key = rel.casefold()
        if key in files or key in always_files:
            return True
        return any(key == d or key.startswith(d + "/") for d in dirs | always_dirs)

    def is_always(self, rel: str) -> bool:
        """Under a `sensitive.always` prefix: sensitive with or without a marker."""
        _, _, always_files, always_dirs = self._folded
        key = rel.casefold()
        return key in always_files or any(key.startswith(d + "/") for d in always_dirs)

    def has_marker(self, text: str) -> bool:
        return bool(self.pattern.search(text))

    def file_marked(self, rel: str) -> bool:
        path = self.root / rel
        try:
            return path.is_file() and self.has_marker(path.read_text(encoding="utf-8", errors="ignore"))
        except OSError:
            return False

    def marked_ancestor(self, rel: str) -> str | None:
        """Nearest folder (relative path) whose README carries the marker."""
        parent = Path(rel).parent
        while parent.parts:
            if self.file_marked((parent / self.readme).as_posix()):
                return parent.as_posix()
            parent = parent.parent
        return None

    def is_sensitive(self, rel: str) -> bool:
        return self.is_listed(rel) or self.file_marked(rel) or self.marked_ancestor(rel) is not None

    @staticmethod
    def generate(config: Config) -> str:
        """Content of the paths file, derived from markers and `sensitive.always`."""
        sensitivity = Sensitivity.load(config, listed=[])
        entries: set[str] = set()
        for rel in iter_note_files(config):
            folder = sensitivity.marked_ancestor(rel)
            if folder is not None:
                entries.add(folder + "/")
            elif sensitivity.file_marked(rel):
                entries.add(rel)
        entries.update(sensitivity.always_files)
        entries.update(d + "/" for d in sensitivity.always_dirs)
        header = [
            "# Generated by dummkopf from sensitivity markers. Do not edit by hand.",
            '# Source: a "' + config.sensitive.marker + '" line in a file or in a README of its folders.',
            '# Usage: rg "<term>" --ignore-file ' + config.sensitive.paths_file,
        ]
        return "\n".join(header + sorted(entries)) + "\n"
