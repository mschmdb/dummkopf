def scoped(brain: Brain, name: str, scope: str, text: str = "In August 2026 there is a deadline.\n") -> None:
    brain.write("topics/" + name + "/README.md", "---\nscope: " + scope + "\n---\n\n# " + name + "\n")
    brain.write("topics/" + name + "/note.md", text)


def test_collision_between_barrier_scopes(repo: Brain) -> None:
    scoped(repo, "job", "work")
    scoped(repo, "holiday", "private")
    entry = next(item for item in links(repo)["collisions"] if item["month"] == "2026-08")
    assert entry["scopes"] == {"work": ["job"], "private": ["holiday"]}


def test_collision_one_line_per_month_and_max_eight(repo: Brain) -> None:
    for index in range(9):
        scoped(repo, f"job{index}", "work")
    scoped(repo, "holiday", "private")
    entries = [item for item in links(repo)["collisions"] if item["month"] == "2026-08"]
    assert len(entries) == 1
    assert len(entries[0]["scopes"]["work"]) == 8
    assert entries[0]["scopes"]["private"] == ["holiday"]


def test_collision_needs_both_scopes_and_ignores_flat_notes(repo: Brain) -> None:
    scoped(repo, "job1", "work")
    scoped(repo, "job2", "work")
    repo.write("notes/whatever.md", "In August 2026 something happens.\n")
    assert links(repo)["collisions"] == []


def test_collision_markdown_german(hub: Brain) -> None:
    scoped(hub, "arbeit", "work", "Im August 2026 ist Deadline.\n")
    scoped(hub, "urlaub", "privat", "Im August 2026 ist Urlaub.\n")
    hub.commit()
    content = write_links(hub.config).read_text()
    assert "work: arbeit × privat: urlaub" in content


def test_sensitive_topic_excluded_and_counted(repo: Brain) -> None:
    repo.write("topics/hidden/README.md", "> SENSITIVE\n\n# Hidden\n")
    repo.write("topics/hidden/note.md", "Acme in August 2026.\n")
    repo.write("topics/open/note.md", "Acme in August 2026.\n")
    repo.write("entities.txt", "Acme\n")
    data = links(repo, 1)
    for item in data["entity_links"] + data["time_links"]:
        assert "topics/hidden" not in item["topics"]
    assert data["sensitive_files"] >= 1 and data["sensitive_topics"] >= 1


def test_cli_json_and_disabled_extra(repo: Brain) -> None:
    repo.write("topics/a/note.md", "x\n")
    repo.commit()
    code, output, _ = invoke(repo, "links", "--json")
    assert code == 0
    assert json.loads(output)["time_links"] == []
    repo.configure("[extras]\nlinks = false\n")
    code, _, error = invoke(repo, "links", "--serious")
    assert code == 2 and "extras" in error
