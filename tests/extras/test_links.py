from __future__ import annotations

import json
from typing import Any

import pytest
from conftest import Brain, invoke

from dummkopf.extras.links import build, write_links


@pytest.fixture
def repo(brain: Brain) -> Brain:
    brain.git_init()
    return brain


@pytest.fixture
def hub(german: Brain) -> Brain:
    german.git_init()
    return german


def links(brain: Brain, min_topics: int | None = None) -> dict[str, Any]:
    brain.commit()
    return dict(build(brain.config, min_topics))


def months(data: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {item["month"]: item for item in data["time_links"]}


def entities(data: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {item["entity"]: item for item in data["entity_links"]}


def test_writes_file_and_is_idempotent(repo: Brain) -> None:
    repo.write("topics/a/README.md", "---\nscope: work\n---\n\n# A\n")
    repo.write("topics/a/note.md", "In August 2026 something happens.\n")
    repo.write("topics/b/README.md", "---\nscope: private\n---\n\n# B\n")
    repo.write("topics/b/note.md", "August 2026 matters here too.\n")
    repo.commit()
    path = write_links(repo.config)
    assert path == repo.root / "LINKS.md"
    first = path.read_text()
    assert "Generated by dummkopf on" in first and "Do not edit by hand." in first
    write_links(repo.config)
    assert path.read_text() == first


def test_german_day_month_year_and_output_name(hub: Brain) -> None:
    hub.write("topics/a/note.md", "Am 06.08.2026 war das so.\n")
    hub.write("topics/b/note.md", "Am 15.08.2026 war das auch so.\n")
    data = links(hub, 2)
    assert months(data)["2026-08"]["topic_count"] == 2
    assert set(months(data)["2026-08"]["topics"]) == {"topics/a", "topics/b"}
    path = write_links(hub.config)
    assert path.name == "KANTEN.md"
    assert "## Zeit-Kanten" in path.read_text()


def test_month_names_and_abbreviations(hub: Brain, repo: Brain) -> None:
    hub.write("topics/a/note.md", "Im September 2026 war das so.\n")
    hub.write("topics/b/note.md", "Sept. 2026 war das auch so.\n")
    assert months(links(hub, 2))["2026-09"]["topic_count"] == 2
    repo.write("topics/a/note.md", "In September 2026 it happened.\n")
    repo.write("topics/b/note.md", "Sep. 2026 as well.\n")
    assert months(links(repo, 2))["2026-09"]["topic_count"] == 2


