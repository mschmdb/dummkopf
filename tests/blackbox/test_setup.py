def test_init_creates_the_scaffold(tmp_path: Path) -> None:
    root = init_brain(tmp_path)
    names = sorted(path.relative_to(root).as_posix() for path in root.rglob("*") if ".git" not in path.parts)
    assert names == [".gitignore", ".sensitive-paths", "AGENTS.md", "CLAUDE.md", "INDEX.md", "archive",
                     "archive/.gitkeep", "bookmarks", "bookmarks/.gitkeep", "dummkopf.toml", "notes",
                     "notes/.gitkeep", "sources", "sources/.gitkeep", "topics", "topics/.gitkeep"]


