"""`init` and `install`: the scaffold, the Git hook and the Claude Code and Codex hook files."""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import pytest

from .conftest import Brain, git, run

REMOTE = "git@github.com:me/brain.git"
CLAUDE_HOOK = 'dummkopf --root "$CLAUDE_PROJECT_DIR" hook agent'
CODEX_HOOK = 'dummkopf --root "$(git rev-parse --show-toplevel)" hook agent'
INSTALLED = "Installed: .git/hooks/pre-commit\nInstalled: .claude/settings.json\nInstalled: .codex/hooks.json\n"


def init_brain(tmp_path: Path, name: str = "newbrain", *args: str) -> Path:
    result = run("init", str(tmp_path / name), "--serious", *args, cwd=tmp_path)
    assert result.code == 0, result.err
    return tmp_path / name


@pytest.fixture
def fresh(tmp_path: Path) -> Path:
    return init_brain(tmp_path, "newbrain", "--remote", REMOTE)


def settings(root: Path, name: str = ".claude/settings.json") -> dict[str, Any]:
    return json.loads((root / name).read_text(encoding="utf-8"))  # type: ignore[no-any-return]


def commands(entries: list[dict[str, Any]]) -> list[str]:
    return [hook["command"] for entry in entries for hook in entry["hooks"]]


