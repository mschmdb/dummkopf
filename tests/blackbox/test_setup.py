def test_replace_command_removes_old_hook_commands_first(fresh: Path) -> None:
    (fresh / ".claude").mkdir()
    old = {"hooks": {
        "PostToolUse": [{"matcher": "Bash", "hooks": [{"type": "command", "command": "python old_sync.py"},
                                                      {"type": "command", "command": "keepme"}]}],
        "Stop": [{"hooks": [{"type": "command", "command": "python old_sync.py --x"}]}]}}
    (fresh / ".claude/settings.json").write_text(json.dumps(old), encoding="utf-8")
    result = run("install", "--serious", "--replace-command", "old_sync.py", cwd=fresh)
    assert result.code == 0
    assert result.out.splitlines()[0] == "Removed 2 old hook command(s)."
    data = settings(fresh)
    flat = commands(data["hooks"]["PostToolUse"])
    assert "keepme" in flat
    assert not any("old_sync.py" in command for command in flat)
    assert "Stop" not in data["hooks"]


def test_replace_command_can_repeat_and_reaches_the_codex_file(fresh: Path) -> None:
    (fresh / ".codex").mkdir()
    old = {"hooks": {"PostToolUse": [{"hooks": [{"type": "command", "command": "old-one"},
                                               {"type": "command", "command": "old-two"}]}]}}
    (fresh / ".codex/hooks.json").write_text(json.dumps(old), encoding="utf-8")
    result = run("install", "--serious", "--replace-command", "old-one", "--replace-command", "old-two", cwd=fresh)
    assert result.out.splitlines()[0] == "Removed 2 old hook command(s)."
    remaining = commands(settings(fresh, ".codex/hooks.json")["hooks"]["PostToolUse"])
    assert len(remaining) == 1
    assert remaining[0].endswith(CODEX_HOOK)


