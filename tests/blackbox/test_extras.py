def test_links_json_has_the_report_keys(brain: Brain) -> None:
    assert list(links_json(brain)) == LINK_KEYS


def test_links_json_is_pretty_printed(brain: Brain) -> None:
    out = brain.run("links", "--json").out
    assert out.startswith('{\n  "time_links": [')
    assert out.endswith("}\n")


def test_links_of_an_empty_brain_is_empty(brain: Brain) -> None:
    assert links_json(brain) == {"time_links": [], "entity_links": [], "collisions": [],
                                 "sensitive_files": 0, "sensitive_topics": 0}


def test_links_writes_the_map_next_to_the_config(brain: Brain) -> None:
    result = brain.run("links")
    assert (result.code, result.out) == (0, "LINKS.md written.\n")
    text = brain.read("LINKS.md")
    assert text.startswith(f"Generated by dummkopf on {TODAY}. Do not edit by hand.\n\n## Time links\n")
    assert "\n## Entity links\n" in text
    assert "\n## Collisions\n" in text
    assert text.endswith("0 sensitive files and 0 sensitive topics excluded.\n")


def test_links_json_does_not_write_the_map(brain: Brain) -> None:
    links_json(brain)
    assert not brain.exists("LINKS.md")


def test_topics_sharing_a_month_in_their_text_are_linked(brain: Brain) -> None:
    topic(brain, "alpha", "work", "Kickoff 2025-03-04.")
    topic(brain, "beta", "work", "Review 2025-03-20.")
    link = month_link(links_json(brain), "2025-03")
    assert link == {"month": "2025-03", "topic_count": 2, "topics": ["topics/alpha", "topics/beta"]}


