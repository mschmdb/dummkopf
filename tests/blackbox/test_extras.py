"""Extras: `links` and `curator`, their JSON keys, scope filtering, sensitivity counts and the off switches."""

from __future__ import annotations

import datetime as dt
import json
from typing import Any

import pytest

from .conftest import Brain

TODAY = dt.date.today().isoformat()
LINK_KEYS = ["time_links", "entity_links", "collisions", "sensitive_files", "sensitive_topics"]
CURATOR_KEYS = ["open_loops", "stale_topics", "conflicting_dates", "stale_active", "sensitive_files",
                "sensitive_topics"]


def doc(title: str, body: str = "body", extra: str = "", updated: str = TODAY, status: str = "active") -> str:
    return (f"---\nupdated: {updated}\nstatus: {status}\nkey_fact: K.\nsummary: K.\naliases: []\nperiod: []\n"
            f"entities: []\n{extra}---\n\n# {title}\n\n{body}\n")


def topic(brain: Brain, name: str, scope: str, body: str = "body", extra: str = "", updated: str = TODAY) -> None:
    brain.write(f"topics/{name}/README.md", doc(name, "readme", f"scope: {scope}\n", updated))
    brain.write(f"topics/{name}/note.md", doc(name + " note", body, extra, updated))


def links_json(brain: Brain, *args: str) -> dict[str, Any]:
    result = brain.run("links", "--json", *args)
    assert result.code == 0, result.err
    return json.loads(result.out)  # type: ignore[no-any-return]


def curator_json(brain: Brain, *args: str) -> dict[str, Any]:
    result = brain.run("curator", "--json", *args)
    assert result.code == 0, result.err
    return json.loads(result.out)  # type: ignore[no-any-return]


def month_link(report: dict[str, Any], month: str) -> dict[str, Any] | None:
    return next((item for item in report["time_links"] if item["month"] == month), None)


