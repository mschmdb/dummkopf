def test_min_topics_raises_the_bar_for_links(brain: Brain) -> None:
    topic(brain, "alpha", "work", "Kickoff 2025-03-04.")
    topic(brain, "beta", "work", "Review 2025-03-20.")
    assert month_link(links_json(brain, "--min-topics", "3"), "2025-03") is None
    assert month_link(links_json(brain, "--min-topics", "2"), "2025-03") is not None


def test_min_topics_comes_from_the_config(brain: Brain) -> None:
    brain.configure("[links]\nmin_topics = 3\n")
