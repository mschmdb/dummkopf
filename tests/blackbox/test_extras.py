def test_open_loop_needs_an_open_word_and_an_old_note(brain: Brain) -> None:
    brain.write("notes/old-loop.md", doc("Old", "First line\nTODO check the invoice\nmore", updated="2020-01-01"))
    brain.write("notes/new-loop.md", doc("New", "TODO check the invoice"))
    brain.write("notes/old-quiet.md", doc("Quiet", "all done", updated="2020-01-01"))
    loops = curator_json(brain)["open_loops"]
    assert loops == [{"path": "notes/old-loop.md", "updated": "2020-01-01", "lines": ["TODO check the invoice"]}]


@pytest.mark.parametrize("word", ["open question", "to check", "unverified", "TBD", "not yet"])
def test_every_open_word_marks_a_loop(brain: Brain, word: str) -> None:
    brain.write("notes/loop.md", doc("Loop", f"This is {word} still", updated="2020-01-01"))
    assert [loop["path"] for loop in curator_json(brain)["open_loops"]] == ["notes/loop.md"]


def test_open_loop_text_shows_the_matching_lines(brain: Brain) -> None:
    brain.write("notes/loop.md", doc("Loop", "TODO call back", updated="2020-01-01"))
    assert "- `notes/loop.md` (2020-01-01)\n  - TODO call back\n" in brain.run("curator").out


def test_open_days_moves_the_open_loop_cutoff(brain: Brain) -> None:
    brain.write("notes/loop.md", doc("Loop", "TODO call back", updated=TODAY))
    assert curator_json(brain)["open_loops"] == []
    three_days_ago = (dt.date.today() - dt.timedelta(days=3)).isoformat()
    brain.write("notes/loop.md", doc("Loop", "TODO call back", updated=three_days_ago))
    assert curator_json(brain)["open_loops"] == []
    assert len(curator_json(brain, "--open-days", "1")["open_loops"]) == 1


def test_open_days_comes_from_the_config(brain: Brain) -> None:
    brain.configure("[curator]\nopen_days = 1\n")
    three_days_ago = (dt.date.today() - dt.timedelta(days=3)).isoformat()
    brain.write("notes/loop.md", doc("Loop", "TODO call back", updated=three_days_ago))
    assert len(curator_json(brain)["open_loops"]) == 1


