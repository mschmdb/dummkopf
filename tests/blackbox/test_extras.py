def test_conflicting_dates_name_notes_with_two_as_of_dates(brain: Brain) -> None:
    brain.write("notes/conflict.md", doc("Conflict", "As of 2025-01-01 it is x.\n\nAs of 2025-02-02 it is y.",
                                         updated="2025-02-02"))
    brain.write("notes/single.md", doc("Single", "As of 2025-01-01 it is x.", updated="2025-01-01"))
    conflicts = curator_json(brain)["conflicting_dates"]
    assert [item["path"] for item in conflicts] == ["notes/conflict.md"]
    assert set(conflicts[0]["dates"]) == {"2025-01-01", "2025-02-02"}


def test_repeating_the_same_as_of_date_is_no_conflict(brain: Brain) -> None:
    brain.write("notes/same.md", doc("Same", "As of 2025-01-01 a.\n\nAs of 2025-01-01 b.", updated="2025-01-01"))
    assert curator_json(brain)["conflicting_dates"] == []


def test_curator_leaves_sensitive_notes_out_and_counts_them(brain: Brain) -> None:
    brain.write("notes/open.md", doc("Open", "TODO fine", updated="2020-01-01"))
    brain.write("notes/marked.md", doc("Marked", "> SENSITIVE\n\nTODO hidden", updated="2020-01-01"))
    scan = curator_json(brain)
    assert [loop["path"] for loop in scan["open_loops"]] == ["notes/open.md"]
    assert scan["sensitive_files"] == 1
    assert "marked" not in brain.run("curator").out
    assert "1 sensitive files and 0 sensitive topics skipped." in brain.run("curator").out


def test_curator_scope_filters_the_scan(brain: Brain) -> None:
    topic(brain, "job", "work", "TODO work item", updated="2020-01-01")
    topic(brain, "home", "private", "TODO home item", updated="2020-01-01")
    paths = [loop["path"] for loop in curator_json(brain, "--scope", "work")["open_loops"]]
    assert paths == ["topics/job/note.md"]
    assert len(curator_json(brain, "--scope", "both")["open_loops"]) == 2


def test_curator_rejects_an_unknown_scope(brain: Brain) -> None:
    assert brain.run("curator", "--scope", "nowhere").code == 2


def test_curator_prompt_is_filled_with_the_brain_settings(brain: Brain) -> None:
    result = brain.run("curator", "--prompt")
    assert result.code == 0
    assert result.out.startswith("# Curator prompt (weekly run)\n")
    assert "`topics/curator/YYYY-WW.md`" in result.out
    assert "LINKS.md" in result.out
    assert "> SENSITIVE" in result.out
    assert ".sensitive-paths" in result.out
    for placeholder in ("{report_dir}", "{links_file}", "{marker}", "{paths_file}", "{updated}", "{key_fact}"):
        assert placeholder not in result.out


def test_curator_prompt_follows_the_config(brain: Brain) -> None:
    brain.configure('[curator]\nreport_dir = "reports/weekly"\n\n[sensitive]\nmarker = "> HUSH"\n\n'
                    '[links]\noutput = "MAP.md"\n')
    out = brain.run("curator", "--prompt").out
    assert "reports/weekly/YYYY-WW.md" in out
    assert "> HUSH" in out
    assert "MAP.md" in out


# --- off switches ----------------------------------------------------------------------------------------------


@pytest.mark.parametrize("command", [("links",), ("links", "--json"), ("curator",), ("curator", "--json"),
                                     ("curator", "--prompt")])
def test_disabled_extras_exit_2_and_name_the_switch(brain: Brain, command: tuple[str, ...]) -> None:
    brain.configure("[extras]\nlinks = false\ncurator = false\n")
    result = brain.run(*command)
    name = command[0]
    assert result.code == 2
    assert result.out == ""
    assert result.err == f"The extra `{name}` is disabled in dummkopf.toml ([extras] {name} = false).\n"


def test_disabling_one_extra_leaves_the_other_working(brain: Brain) -> None:
    brain.configure("[extras]\nlinks = false\n")
    assert brain.run("links").code == 2
    assert brain.run("curator").code == 0


def test_disabled_links_do_not_write_the_map(brain: Brain) -> None:
    brain.configure("[extras]\nlinks = false\n")
    brain.run("links")
    assert not brain.exists("LINKS.md")
