// Copies the design tokens of schmidbauer.dev into src/tokens.css. That repo is private, so the site keeps a
// copy; never edit the copy by hand, run this again instead:
//   node scripts/sync-tokens.mjs [path/to/schmidbauer-dev]   (default: ~/Sites/schmidbauer-dev)

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const source = process.argv[2] ?? join(homedir(), "Sites", "schmidbauer-dev");
const css = readFileSync(join(source, "src", "app.css"), "utf8");
const commit = execFileSync("git", ["-C", source, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();

/** The whole `selector { … }` block, braces included. @param {string} selector */
function block(selector) {
  const start = css.indexOf(selector + " {");
  if (start === -1) throw new Error("Selector not found in app.css: " + selector);
  const end = css.indexOf("\n}", start);
  return css.slice(start, end + 2);
}

const header = "/* Design tokens of schmidbauer.dev (src/app.css at " + commit + "). Generated by scripts/sync-tokens.mjs;\n"
  + "   do not edit by hand. Components use these tokens only, never raw color values. */\n\n";
writeFileSync(new URL("../src/tokens.css", import.meta.url), header + block(":root") + "\n\n" + block("[data-theme='dark']") + "\n");
console.log("tokens.css updated from " + commit);
